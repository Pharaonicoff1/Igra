/**
 * Тип задания по id.
 * @param {string} id
 * @returns {typeof MISSION_TYPES[number]|null}
 */
export function missionType(id) {
  for (const t of MISSION_TYPES) if (t.id === id) return t;
  return null;
}

/**
 * Сколько единиц прогресса нужно для задания. У streakLevel в таблице лежит
 * индекс ступени серии, а прогресс меряется длиной серии — порог берётся из
 * STREAK_LEVELS, чтобы задание не разошлось с самой серией при правке её таблицы.
 * @param {string} typeId
 * @param {string} tier
 * @returns {number|null} null — тип на этой сложности не выдаётся
 */
export function missionTarget(typeId, tier) {
  const t = missionType(typeId);
  if (!t || !(tier in t.targets)) return null;
  const raw = t.targets[tier];
  if (typeId === 'streakLevel') {
    const step = STREAK_LEVELS[Math.min(Math.max(raw, 1), STREAK_LEVELS.length - 1)];
    return step.from;
  }
  return raw;
}

/**
 * Постоянная прокачка множителя очков.
 *
 * Не бустер на время и не награда за игру: купленный уровень действует на КАЖДОМ
 * забеге с первой же посадки и никогда не сбрасывается. Уровни берутся строго по
 * очереди — перепрыгнуть через уровень нельзя, поэтому cost читается как «цена
 * перехода НА этот уровень с предыдущего», а не как накопительная стоимость.
 *
 * Вынесено таблицей, а не формулой: кривая цен подбирается на глаз под баланс
 * добычи осколков, и её проще править числами.
 *
 * @type {{level:number, value:number, cost:number}[]}
 */
export const MULTIPLIER_LEVELS = [
  { level: 0, value: 1,    cost: 0 },   // стартовый, есть у всех
  { level: 1, value: 1.2,  cost: 40 },
  { level: 2, value: 1.4,  cost: 90 },
  { level: 3, value: 1.6,  cost: 160 },
  { level: 4, value: 1.8,  cost: 260 },
  { level: 5, value: 2,    cost: 400 },
  { level: 6, value: 2.25, cost: 600 },
  { level: 7, value: 2.5,  cost: 900 },
];

/** Максимальный уровень прокачки. */
export const MAX_MULTIPLIER_LEVEL = MULTIPLIER_LEVELS.length - 1;

/**
 * Привести уровень к допустимому диапазону. Единственное место, где чинится
 * битое/устаревшее значение из хранилища.
 * @param {number} level
 * @returns {number} целое в [0, MAX_MULTIPLIER_LEVEL]
 */
export function clampMultiplierLevel(level) {
  const n = Math.round(Number(level));
  if (!Number.isFinite(n)) return 0;
  return Math.min(Math.max(n, 0), MAX_MULTIPLIER_LEVEL);
}

/**
 * Множитель очков на данном уровне.
 * @param {number} level
 * @returns {number}
 */
export function multiplierValue(level) {
  return MULTIPLIER_LEVELS[clampMultiplierLevel(level)].value;
}

/**
 * Цена следующего уровня.
 * @param {number} level текущий уровень
 * @returns {number|null} null — уже максимум, покупать нечего
 */
export function multiplierUpgradeCost(level) {
  const cur = clampMultiplierLevel(level);
  if (cur >= MAX_MULTIPLIER_LEVEL) return null;
  return MULTIPLIER_LEVELS[cur + 1].cost;
}

/**
 * Множитель для показа: всегда хотя бы один знак после запятой.
 *
 * Иначе лестница читалась бы рвано — «x2 → x2.25» выглядит как две разные
 * величины, а «x2.0 → x2.25» как соседние ступени одной шкалы.
 *
 * @param {number} value
 * @returns {string}
 */
export function formatMultiplier(value) {
  const s = value.toFixed(2);
  return s.endsWith('0') ? s.slice(0, -1) : s;
}

