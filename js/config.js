/**
 * За сколько секунд тлеющая лава сжигает космонавта на ДАННОМ теле.
 *
 * У астероида таймер свой и заметно длиннее планетного. Причина не в жалости,
 * а в геометрии: он маленький, стоит сбоку, и окно отрыва обратно на маршрут
 * занимает считанные проценты окружности — на планетных 2.5с уйти с него
 * физически не успевал никто (замер в CFG.asteroid). Единственное место, где
 * этот выбор делается: и таймер смерти, и виньетка, и валидатор спавна обязаны
 * спрашивать здесь, иначе они разойдутся между собой.
 *
 * @param {{asteroid?: boolean}|null} planet
 * @returns {number} секунды
 */
export function smolderTimeFor(planet) {
  return planet && planet.asteroid ? CFG.asteroid.smolderDeathTime : CFG.lava.smolderDeathTime;
}

/**
 * Ступени серии за точные прыжки. Таблицей, а не формулой — как
 * MULTIPLIER_LEVELS: кривую подбирают на глаз, и править числа проще.
 *
 * Пороги редкие и растут нелинейно (3 / 6 / 10): серия должна читаться как
 * достижение, а не капать за каждый второй прыжок.
 *
 * ЗАМЕР за 50 планет (бот, тот же маршрут с серией и без неё):
 *   все прыжки точные  -> x2.73 к счёту (аналитически x2.75);
 *   точны ~50%          -> x1.07 — три точных подряд выпадают редко.
 * Идеальная игра превышает ориентир x2.5. Поджать минимальной правкой:
 * потолок x2.5 вместо x3 на том же пороге 10 -> x2.34. Перенос x3 на порог
 * 15 почти не помогает (x2.65): основную прибавку даёт длинный хвост забега.
 * Пока оставлены стартовые значения из ТЗ — решение за дизайном.
 *
 * @type {{from:number, value:number}[]} from — порог ТОЧНЫХ прыжков подряд
 */
export const STREAK_LEVELS = [
  { from: 0,  value: 1 },    // серии фактически нет, бейдж скрыт
  { from: 3,  value: 1.5 },
  { from: 6,  value: 2 },
  { from: 10, value: 3 },
];

/**
 * Множитель серии для данной длины.
 * @param {number} streak сколько точных прыжков подряд
 * @returns {number}
 */
export function streakMultiplier(streak) {
  let value = 1;
  for (const step of STREAK_LEVELS) {
    if (streak >= step.from) value = step.value;
  }
  return value;
}

/**
 * Номер ступени (0 — серии нет). По нему решается, был ли переход на новый
 * уровень: сравнивать сами множители ненадёжно, если два уровня совпадут.
 * @param {number} streak
 * @returns {number} индекс в STREAK_LEVELS
 */
export function streakLevelIndex(streak) {
  let index = 0;
  for (let i = 0; i < STREAK_LEVELS.length; i++) {
    if (streak >= STREAK_LEVELS[i].from) index = i;
  }
  return index;
}

