/**
 * Постоянная прокачка множителя очков.
 *
 * Не бустер на время и не награда за игру: купленный уровень действует на КАЖДОМ
 * забеге с первой же посадки и никогда не сбрасывается. Уровни берутся строго по
 * очереди — перепрыгнуть через уровень нельзя, поэтому cost читается как «цена
 * перехода НА этот уровень с предыдущего», а не как накопительная стоимость.
 *
 * Вынесено таблицей, а не формулой: кривая цен подбирается на глаз под баланс
 * добычи осколков, и её проще править числами.
 *
 * @type {{level:number, value:number, cost:number}[]}
 */
export const MULTIPLIER_LEVELS = [
  { level: 0, value: 1,    cost: 0 },   // стартовый, есть у всех
  { level: 1, value: 1.2,  cost: 40 },
  { level: 2, value: 1.4,  cost: 90 },
  { level: 3, value: 1.6,  cost: 160 },
  { level: 4, value: 1.8,  cost: 260 },
  { level: 5, value: 2,    cost: 400 },
  { level: 6, value: 2.25, cost: 600 },
  { level: 7, value: 2.5,  cost: 900 },
];

/** Максимальный уровень прокачки. */
export const MAX_MULTIPLIER_LEVEL = MULTIPLIER_LEVELS.length - 1;

/**
 * Привести уровень к допустимому диапазону. Единственное место, где чинится
 * битое/устаревшее значение из хранилища.
 * @param {number} level
 * @returns {number} целое в [0, MAX_MULTIPLIER_LEVEL]
 */
export function clampMultiplierLevel(level) {
  const n = Math.round(Number(level));
  if (!Number.isFinite(n)) return 0;
  return Math.min(Math.max(n, 0), MAX_MULTIPLIER_LEVEL);
}

