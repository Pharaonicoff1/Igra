/**
 * Номер сектора (с нуля) по числу пройденных планет. Считается от
 * planetsPassed, как вся сложность, а не от очков: очки зависят от покупок.
 *
 * Эта же функция красит планеты: порядковый номер планеты в цепочке равен
 * числу пройденных планет в момент посадки на неё, поэтому планета знает свой
 * сектор с рождения, и граница видна заранее — следующая за ней уже другого
 * цвета.
 *
 * @param {number} passed пройдено планет ИЛИ номер планеты в цепочке (с нуля)
 * @returns {number} 0, 1, 2, ... без потолка
 */
export function sectorIndexFor(passed) {
  return Math.floor(Math.max(passed, 0) / CFG.sector.planets);
}

/**
 * Какая палитра у сектора с данным номером: первые идут по порядку, дальше —
 * по кругу начиная с CFG.sector.loopFrom. Номер сектора при этом растёт.
 * @param {number} index номер сектора с нуля
 * @param {number} count сколько секторов в теме
 * @returns {number} индекс в theme().sectors
 */
export function sectorSlot(index, count) {
  if (index < count) return Math.max(index, 0);
  const from = Math.min(Math.max(CFG.sector.loopFrom, 0), count - 1);
  return from + (index - from) % (count - from);
}

/**
 * Палитра сектора данной темы.
 * @param {typeof THEMES.space} T
 * @param {number} index номер сектора с нуля
 * @returns {typeof THEMES.space.sectors[number]}
 */
export function sectorOf(T, index) {
  return T.sectors[sectorSlot(index, T.sectors.length)];
}

